// Parse the ```variant_fields``` JSON block emitted by the fact extractor (Phase B).
function parseVariantFields(text) {
  if (!text) return null;
  let raw = null;
  const fenced = text.match(/```variant_fields\s*([\s\S]*?)```/i);
  if (fenced) raw = fenced[1];
  if (!raw) {
    const obj = text.match(/\{[^{}]*"(?:family|upperKO|lowerKO|couponBarrier|knockIn|participation)"[\s\S]*?\}/);
    if (obj) raw = obj[0];
  }
  if (!raw) return null;
  try { return JSON.parse(raw.trim()); } catch (_) { return null; }
}
function stripVariantFields(text) {
  return (text || "").replace(/```variant_fields[\s\S]*?```/gi, "").trim();
}

