/* ─── Post-processing (deterministic fixes) ─── */
function postProcess(text) {
  if (!text) return text;
  return text
    .replace(/\bผม\b(?!\/ดิฉัน)/g, "ผม/ดิฉัน")
    .replace(/\bดิฉัน\b(?! )/g, (m, offset, str) => {
      const before = str.slice(Math.max(0, offset - 6), offset);
      return before.includes("ผม/") ? m : "ผม/ดิฉัน";
    })
    .replace(/\bครับ\b(?!\/ค่ะ)/g, "ครับ/ค่ะ")
    .replace(/\bค่ะ\b(?! )/g, (m, offset, str) => {
      const before = str.slice(Math.max(0, offset - 5), offset);
      return before.includes("ครับ/") ? m : "ครับ/ค่ะ";
    });
}

