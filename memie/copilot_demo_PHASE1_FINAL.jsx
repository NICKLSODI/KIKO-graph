function PillGroup({ value, onChange, options, multi }) {
  const isSelected = (v) => multi ? value.includes(v) : value === v;
  const toggle = (v) => {
    if (multi) onChange(value.includes(v) ? value.filter(x => x !== v) : [...value, v]);
    else onChange(v);
  };
  return (
    <div style={{ display: "flex", flexWrap: "wrap", gap: 8 }}>
      {options.map(o => {
        const val = typeof o === "string" ? o : o.value;
        const label = typeof o === "string" ? o : o.label;
        const sel = isSelected(val);
        return (
          <button key={val} onClick={() => toggle(val)} style={{
            padding: "8px 13px", borderRadius: 20, fontSize: 13.5, cursor: "pointer",
            border: `1px solid ${sel ? C.teal : C.border}`, background: sel ? C.tealLight : C.white,
            color: sel ? C.teal : C.text, fontWeight: sel ? 600 : 400,
          }}>{label}</button>
        );
      })}
    </div>
  );
}

function FileDrop({ file, onFile, onClear }) {
  const handleChange = (e) => {
    const f = e.target.files?.[0];
    if (!f) return;
    const allowed = ["application/pdf", "image/png", "image/jpeg", "image/webp"];
    if (!allowed.includes(f.type)) { alert("รองรับเฉพาะไฟล์ PDF, PNG, JPG, WEBP เท่านั้น"); return; }
    if (f.size > 20 * 1024 * 1024) { alert("ไฟล์ต้องไม่เกิน 20MB"); return; }
    const reader = new FileReader();
    reader.onload = () => onFile({ data: reader.result.split(",")[1], mediaType: f.type, name: f.name });
    reader.readAsDataURL(f);
  };
  if (file) return (
    <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", padding: "12px 14px", background: C.tealLight, border: `1px solid ${C.tealBorder}`, borderRadius: 10 }}>
      <span style={{ color: C.teal, fontSize: 14 }}>📄 {file.name}</span>
      <button onClick={onClear} style={{ background: "none", border: "none", cursor: "pointer", color: C.muted, fontSize: 18, lineHeight: 1 }}>×</button>
    </div>
  );
  return (
    <label style={{ display: "flex", alignItems: "center", justifyContent: "center", gap: 8, padding: "20px", border: `1.5px dashed ${C.border}`, borderRadius: 10, cursor: "pointer", color: C.muted, fontSize: 14 }}>
      📁 นำเข้าไฟล์เอกสาร (รูปแบบ PDF, PNG, JPG, WEBP — ขนาดไม่เกิน 20MB)
      <input type="file" accept=".pdf,.png,.jpg,.jpeg,.webp" onChange={handleChange} style={{ display: "none" }} />
    </label>
  );
}

