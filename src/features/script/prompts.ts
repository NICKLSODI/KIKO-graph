export interface PersonaOpts {
  relationshipStatus: string
  ageRange: string
  financialKnowledge: string
  investmentGoal: string
  riskProfile: string
  experienceLevel: string
  assetTier: string
  concerns: string[]
  tone: string
  focus: string[]
}

export function buildPersonaContext(opts: PersonaOpts): string {
  const expLabel = EXPERIENCE_OPTIONS.find((o) => o.value === opts.experienceLevel)?.label || 'ไม่ระบุ'
  const assetLabel = ASSET_OPTIONS.find((o) => o.value === opts.assetTier)?.label || 'ไม่ระบุ'
  const toneRule = TONE_GUIDANCE[opts.tone] || TONE_GUIDANCE['เป็นทางการเชิงวิชาชีพ (Professional)']
  const fieldBlock = [
    `สถานะทางข้อผูกพันของลูกค้า: ${opts.relationshipStatus} → คำสั่งกำกับ: ${RELATIONSHIP_INSTRUCTION[opts.relationshipStatus] || ''}`,
    `ช่วงอายุ: ${opts.ageRange}`,
    `ระดับความรู้ความเข้าใจด้านการเงิน: ${opts.financialKnowledge} → คำสั่งกำกับ: ${KNOWLEDGE_INSTRUCTION[opts.financialKnowledge] || ''}`,
    `วัตถุประสงค์ในการลงทุน: ${opts.investmentGoal} → คำสั่งกำกับ: ${GOAL_INSTRUCTION[opts.investmentGoal] || ''}`,
    `Risk Profile: ${opts.riskProfile} → คำสั่งกำกับ: ${RISK_INSTRUCTION[opts.riskProfile] || ''}`,
    `ประสบการณ์และระดับสินทรัพย์ (${expLabel} / ${assetLabel}) → คำสั่งกำกับ: ${depthAndTone(opts.experienceLevel, opts.assetTier)}`,
  ].join('\n\n')
  const concernBlock = opts.concerns.length ? `ข้อกังวลของลูกค้าที่ต้องถูกพูดถึงและคลี่คลายครบทุกข้อ: ${opts.concerns.join(', ')}` : ''
  const focusBlock = opts.focus.length ? `ประเด็นที่ต้องเน้นเป็นพิเศษ: ${opts.focus.join(', ')}` : ''
  return [
    `ข้อมูล Client Profile Analysis พร้อมคำสั่งกำกับการใช้งาน:\n\n${fieldBlock}`,
    concernBlock,
    focusBlock,
    `ข้อกำหนดด้านน้ำเสียงและการใช้ภาษา: ${toneRule}`,
    'ข้อมูลทุกรายการข้างต้นมีความสำคัญสูงสุดเท่ากัน ต้องสะท้อนอยู่ในเนื้อหาทุกส่วน',
  ].filter(Boolean).join('\n\n')
}

