export function buildScriptPrompt(
  format: ScriptFormatKey,
  data: RetrievedProductData,
  persona: PersonaOpts,
  durationMinutes: number,
): string {
  const facts = factsText(data)
  const personaCtx = buildPersonaContext(persona)
  switch (format) {
    case 'callScript':
      return callScriptPrompt(facts, personaCtx, durationMinutes)
    case 'lineMessage':
      return lineMessagePrompt(facts, personaCtx)
    case 'email':
      return emailPrompt(facts, personaCtx)
    case 'faq':
      return faqPrompt(facts, personaCtx)
    case 'rolePlay':
      return rolePlayPrompt(facts, personaCtx)
  }
}
